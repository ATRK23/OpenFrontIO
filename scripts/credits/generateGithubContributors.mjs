import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repository = process.env.GITHUB_REPOSITORY ?? "openfrontio/OpenFrontIO";
const outputPath = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../../src/client/generated/CreditsGithubContributors.ts",
);
const configPath = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "credits-github-contributors.config.json",
);
const githubLogin = /^[A-Za-z\d](?:[A-Za-z\d-]{0,37})?$/;

/** @typedef {{ login: string; type?: string }} GitHubContributor */

async function readExcludedLogins() {
  const config = JSON.parse(await readFile(configPath, "utf8"));
  if (!Array.isArray(config.excludedLogins)) {
    throw new Error(
      "credits-github-contributors.config.json requires excludedLogins to be an array",
    );
  }
  const invalidLogin = config.excludedLogins.find(
    (login) => typeof login !== "string" || !githubLogin.test(login),
  );
  if (invalidLogin !== undefined) {
    throw new Error(
      `Invalid excluded GitHub login: ${JSON.stringify(invalidLogin)}`,
    );
  }
  return new Set(config.excludedLogins.map((login) => login.toLowerCase()));
}

async function fetchContributors(excludedLogins) {
  /** @type {GitHubContributor[]} */
  const contributors = [];
  const headers = {
    Accept: "application/vnd.github+json",
    "X-GitHub-Api-Version": "2026-03-10",
  };
  if (process.env.GITHUB_TOKEN) {
    headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  }

  for (let page = 1; ; page += 1) {
    const response = await fetch(
      `https://api.github.com/repos/${repository}/contributors?anon=1&per_page=100&page=${page}`,
      { headers },
    );
    if (!response.ok) {
      throw new Error(
        `GitHub contributors request failed (${response.status}): ${await response.text()}`,
      );
    }
    const pageContributors = await response.json();
    if (!Array.isArray(pageContributors)) {
      throw new Error("GitHub contributors response was not an array");
    }
    contributors.push(...pageContributors);
    if (pageContributors.length < 100) break;
  }

  return [
    ...new Set(
      contributors
        .filter(
          (contributor) =>
            contributor.type === "User" && githubLogin.test(contributor.login),
        )
        .filter(
          (contributor) => !excludedLogins.has(contributor.login.toLowerCase()),
        )
        .map((contributor) => contributor.login),
    ),
  ].sort((left, right) => left.localeCompare(right));
}

function render(contributors) {
  const entries = contributors
    .map(
      (login) =>
        `  { login: ${JSON.stringify(login)}, profileUrl: ${JSON.stringify(`https://github.com/${login}`)} },`,
    )
    .join("\n");
  return `// Generated by scripts/credits/generateGithubContributors.mjs. Do not edit manually.\n// Source: GitHub's repository contributors API; anonymous authors and bots are excluded.\n\nexport type GitHubContributor = {\n  login: string;\n  profileUrl: string;\n};\n\nexport const githubContributors: readonly GitHubContributor[] = [\n${entries}\n];\n`;
}

const generated = render(await fetchContributors(await readExcludedLogins()));

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== generated) {
    console.error(
      `${outputPath} is out of date; run this script without --check.`,
    );
    process.exitCode = 1;
  }
} else {
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, generated);
}
